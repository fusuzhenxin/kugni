const fs = require("node:fs");
const path = require("node:path");
const project = path.resolve(__dirname, "..");
const postcss = require(path.join(project, "web/node_modules/postcss"));

// Base first, then feature rules. Keep the complete bundle scoped so that
// management controls cannot change the approved public site's presentation.
const sheets = [
  "app/globals.css",
  "styles/account.css",
  "styles/tools.css",
  "styles/admin.css",
  "styles/workspace-select.css",
  "styles/workspace-login.css",
];
const css = sheets
  .map((file) => {
    const ast = postcss.parse(
      fs.readFileSync(path.join(project, "web/src", file), "utf8"),
    );
    ast.walkAtRules("import", (rule) => rule.remove());
    ast.walkRules((rule) => {
      if (rule.parent?.type === "atrule" && /keyframes$/.test(rule.parent.name))
        return;
      rule.selector = rule.selector.replace(
        /:root|(?<![\w-])(?:html|body)(?![\w-])/g,
        ":scope",
      );
    });
    return `/* Source: ${file} */\n${ast.toString()}`;
  })
  .join("\n");
require(path.join(project, "web/node_modules/prettier"))
  .format(
    `/* Generated by scripts/build-platform-styles.cjs. Edit the source sheets. */\n@scope (.platform-site) {\n${css}\n}\n`,
    { parser: "css" },
  )
  .then((formatted) =>
    fs.writeFileSync(
      path.join(project, "web/src/styles/platform.css"),
      formatted,
    ),
  )
  .catch((error) => {
    console.error(error);
    process.exitCode = 1;
  });
